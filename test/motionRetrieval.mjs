import assert from 'node:assert/strict';
import {loadCatalog,selectRecipes} from '../scripts/motion-recipe.mjs';
import {evaluateRetrieval,regressionFailures,THRESHOLDS} from '../scripts/evaluate-motion-retrieval.mjs';
import {readFileSync} from 'node:fs';
const catalog=loadCatalog();
const benchmark=JSON.parse(readFileSync(new URL('../data/motion-recipes/query-benchmark.v1.json',import.meta.url),'utf8'));
assert.ok(benchmark.cases.length>=50);
const top=q=>selectRecipes(catalog,q)[0]?.id;
const empty=q=>assert.deepEqual(selectRecipes(catalog,q),[],q);
assert.equal(top('控えめで高級感のある成功演出。弾ませない'),'success-burst');
assert.equal(top('派手すぎない完了の合図'),'success-burst');
assert.equal(top('A subtle checkmark to show the upload completed'),'success-burst');
assert.equal(top('No reward celebration; just show progress'),'progress-fill');
assert.equal(top('Do not show an error animation, just a quiet loading state'),'loading-breathe');
assert.equal(top('入力のフォーカスではなく、クリックの反応だけ欲しい'),'press-release');
assert.equal(top('Not too quiet, make the sticker pop'),'sticker-pop');
assert.equal(top('ステッカーが弾けるように登場する'),'sticker-pop');
assert.equal(top('Without a toast, confirm that saving succeeded'),'success-burst');
empty('静かで上品な感じにして');
empty('Not flashy, not loud, not energetic');
empty('夕飯の献立を考えてほしい');
empty('Please explain what parallax means');
empty('ボタンを押したときの音を作って');
assert.ok(!selectRecipes(catalog,'派手じゃないけど、かわいいマスコットの挨拶').slice(0,3).some(x=>x.id==='reward-reveal'));
assert.deepEqual(selectRecipes(catalog,'progress',{limit:0}),[]);
const explain=selectRecipes(catalog,'No reward celebration; just show progress');
assert.ok(explain[0].why.every(x=>typeof x==='string'&&x.length>0));
const results=evaluateRetrieval(catalog,benchmark,selectRecipes);
assert.deepEqual(regressionFailures(results.metrics),[],JSON.stringify(results.metrics));
assert.ok(regressionFailures({...results.metrics,top1:0})[0].includes('top1'));
const bad=structuredClone(benchmark);bad.cases.push(structuredClone(bad.cases[0]));
assert.throws(()=>evaluateRetrieval(catalog,bad,selectRecipes),/duplicate/);
const badId=structuredClone(benchmark);badId.cases[0].forbiddenTopIds=['recipe-does-not-exist'];
assert.throws(()=>evaluateRetrieval(catalog,badId,selectRecipes),/unknown recipe id/);
console.log('motion retrieval: PASSED ('+results.counts.cases+' prompts; top1 '+(results.metrics.top1*100).toFixed(1)+'%; gates '+Object.keys(THRESHOLDS).length+')');
